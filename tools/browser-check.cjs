// Run against tools/preview.html with a local HTTP server.
const {chromium} = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1280,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8766/tools/preview.html');
  const panel=page.locator('jebao-studio-panel');
  await panel.locator('.card').first().waitFor();
  await panel.getByText(/Programm-Modus aktiv/).waitFor();
  if(!await panel.locator('input[type=number]').first().isDisabled())throw new Error('Program mode permits manual input');
  await panel.getByRole('button',{name:'Auf Manual umstellen',exact:true}).click();
  const numeric=panel.locator('input[type=number]').first();
  await numeric.fill('73');await numeric.press('Enter');
  if(await numeric.inputValue()!=='73')throw new Error('Number input reset');
  await numeric.blur();
  await panel.locator('.card').first().locator('summary').click();
  await panel.getByRole('combobox',{name:'Betriebsart'}).first().selectOption('on');
  await panel.getByText(/Programm-Modus aktiv/).waitFor();
  await panel.getByRole('button',{name:'Auf Manual umstellen',exact:true}).click();
  await panel.getByRole('button',{name:'Fütterungspause',exact:true}).first().click();
  await panel.getByRole('button',{name:'Fütterung beenden',exact:true}).click();
  const firstCard=panel.locator('.card').first();
  await firstCard.locator('.mode-picker').filter({hasText:'Wellenmodus'}).locator('select').selectOption('constant_flow');
  if(await firstCard.getByLabel('Wellenfrequenz',{exact:true}).count())throw new Error('Constant mode shows wave frequency');
  await firstCard.locator('.mode-picker').filter({hasText:'Wellenmodus'}).locator('select').selectOption('sine_wave');
  const frequency=firstCard.locator('input[type=range]').nth(1);
  await frequency.evaluate(input=>{input.value='61';input.dispatchEvent(new Event('input',{bubbles:true}));input.dispatchEvent(new Event('change',{bubbles:true}))});
  if(await firstCard.locator('input[type=number]').nth(1).inputValue()!=='61')throw new Error('Frequency change lost');
  await panel.getByRole('button',{name:'Ausschalten',exact:true}).first().click();
  await panel.getByRole('button',{name:'Einschalten',exact:true}).first().click();
  await panel.getByRole('button',{name:'Gruppen',exact:true}).click();
  await panel.getByText('Unterschiedliche Modi',{exact:true}).waitFor({state:'attached'});
  await panel.getByRole('button',{name:'Alle aus',exact:true}).click();
  await panel.getByText(/2 geändert, 0 fehlgeschlagen/).waitFor();
  await panel.getByRole('button',{name:'Pumpen',exact:true}).click();
  // Group drafts must survive HA updates even after the checkbox loses focus.
  await panel.getByRole('button',{name:'Gruppen',exact:true}).click();
  await panel.getByRole('button',{name:'+ Neue Gruppe',exact:true}).click();
  await panel.getByRole('textbox',{name:'Gruppenname'}).fill('Mobile Testgruppe');
  const checks=panel.locator('.editor input[type=checkbox]');
  await checks.nth(0).check();await checks.nth(0).blur();
  const update=()=>page.evaluate(()=>{const p=document.querySelector('jebao-studio-panel');p.hass={...p._hass}});
  await update();
  if(!await checks.nth(0).isChecked())throw new Error('Selection reset after HA update');
  await checks.nth(1).check();await checks.nth(1).blur();await update();
  if(await checks.filter({visible:true}).count()!==2)throw new Error('Group members missing');
  await page.evaluate(()=>{const p=document.querySelector('jebao-studio-panel'),original=p._hass.callWS;p._hass.callWS=async message=>{if(message.type==='jebao_studio/group_save'){p._hass.callWS=original;throw new Error('Simulierter Speicherfehler')}return original(message)}});
  await panel.getByRole('button',{name:'Speichern',exact:true}).click();
  await panel.getByText('Simulierter Speicherfehler',{exact:true}).waitFor();
  if(!await checks.nth(0).isChecked()||!await checks.nth(1).isChecked())throw new Error('Failed save discarded draft');
  await panel.getByRole('button',{name:'Speichern',exact:true}).click();
  const group=panel.locator('.card').filter({has:page.getByRole('heading',{name:'Mobile Testgruppe',exact:true})});
  await group.waitFor();
  await group.getByRole('button',{name:'Bearbeiten',exact:true}).click();
  if(!await checks.nth(0).isChecked()||!await checks.nth(1).isChecked())throw new Error('Saved group lost members');
  await checks.nth(0).uncheck();await panel.getByRole('textbox',{name:'Gruppenname'}).fill('Discard this edit');
  await panel.getByRole('button',{name:'Abbrechen',exact:true}).click();
  await group.getByRole('button',{name:'Bearbeiten',exact:true}).click();
  if(!await checks.nth(0).isChecked())throw new Error('Cancel mutated the saved group');
  await panel.getByRole('button',{name:'Löschen',exact:true}).click();
  await group.waitFor({state:'detached'});
  await panel.getByRole('button',{name:'+ Neue Gruppe',exact:true}).click();
  await panel.getByRole('button',{name:'Speichern',exact:true}).click();
  await panel.getByText('Bitte einen Gruppennamen und mindestens eine Pumpe auswählen.',{exact:true}).waitFor();
  await panel.getByRole('button',{name:'Abbrechen',exact:true}).click();
  await panel.getByRole('button',{name:'Pumpen',exact:true}).click();
  for(const width of [320,360,390,430,768]){
    await page.setViewportSize({width,height:844});
    await update();
    if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Horizontal overflow at '+width);
  }
  await page.evaluate(()=>{const p=document.querySelector('jebao-studio-panel');p.error='';p.notice='';p.render()});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'docs/studio-preview-mobile.png',fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile horizontal overflow');
  await page.setViewportSize({width:1280,height:1000});
  await page.screenshot({path:'docs/studio-preview.png',fullPage:true});
  await browser.close();
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('Desktop/mobile 320–1280px, pump controls, groups create/edit/cancel/delete, HA draft preservation and validation passed.');
})().catch(error=>{console.error(error);process.exitCode=1});
